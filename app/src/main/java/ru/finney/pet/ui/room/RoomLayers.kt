package ru.finney.pet.ui.room

import androidx.annotation.DrawableRes
import androidx.compose.runtime.Immutable
import ru.finney.pet.R

/**
 * Прямоугольник в долях холста комнаты: 0 — левый верхний угол, 1 — правый нижний.
 *
 * Доли, а не пиксели, потому что слои в ресурсах обрезаны по содержимому и своих
 * координат не помнят: положение живёт здесь. Тот же приём, что у точек вращения
 * конечностей в PetSkin.
 */
@Immutable
data class RelRect(val left: Float, val top: Float, val right: Float, val bottom: Float) {
    val width: Float get() = right - left
    val height: Float get() = bottom - top

    fun shiftedX(dx: Float) = RelRect(left + dx, top, right + dx, bottom)
    fun shiftedY(dy: Float) = RelRect(left, top + dy, right, bottom + dy)

    /** Отражение по горизонтали вокруг вертикали [axis] — доли той же ширины. */
    fun mirrored(axis: Float) = RelRect(2f * axis - right, top, 2f * axis - left, bottom)

    /** Промежуточный прямоугольник: [t] = 0 — этот, 1 — [to]. */
    fun lerp(to: RelRect, t: Float) = RelRect(
        left + (to.left - left) * t,
        top + (to.top - top) * t,
        right + (to.right - right) * t,
        bottom + (to.bottom - bottom) * t,
    )
}

/** Слой комнаты: картинка и место, где она лежит на холсте. */
@Immutable
data class RoomLayer(@DrawableRes val image: Int, val rect: RelRect) {
    fun shiftedX(dx: Float) = copy(rect = rect.shiftedX(dx))

    fun shiftedY(dy: Float) = copy(rect = rect.shiftedY(dy))
}

/**
 * Комната, которая сейчас на экране.
 *
 * Холст у всех один — стена, пол и окно из выбранного интерьера, — а комнату
 * делает предмет: «кухня (при нажатии на кнопку появляется стол)», «ванная
 * (при нажатии на кнопку появляется ванна)», так подписано в макете. Поэтому стол
 * и ванна лежат на холсте дизайнера в одном месте. Чтобы комнаты не читались
 * как одна, где переставили мебель, они стоят в ряд, и переход между ними
 * съезжает вбок (RoomScene).
 *
 * Порядок значений — порядок комнат в ряду и кнопок внизу, слева направо.
 */
enum class RoomSpot(
    /** Стоит ли в комнате торшер. На кухне его нет: там стол у окна. */
    val hasLamp: Boolean,
    /**
     * Тёплый свет сверху, от лампы под потолком за кадром. На кухне без него
     * было темно и грустно, а торшер рядом со столом ставить некуда.
     */
    val ceilingLight: Boolean = false,
    /** Есть ли окно. В ванной его нет: светит только торшер. */
    val hasWindow: Boolean,
) {
    /**
     * Игровая: игрушки на полу, питомец гуляет. Это спальня в зеркале — торшер справа,
     * окно слева (RoomScene): без своего предмета одинаковая стена выдавала бы, что
     * комната та же. Свой предмет — ковёр, ящик или полка — ждём от дизайнеров.
     */
    PLAY(hasLamp = true, hasWindow = true),

    /** Стол: здесь кормят. */
    KITCHEN(hasLamp = false, hasWindow = true, ceilingLight = true),

    /** Ванна с пеной: здесь моют. */
    BATH(hasLamp = true, hasWindow = false),

    /** Спальня с капсулой и торшером: здесь спят и украшают комнату. Сон — у края ряда. */
    LIVING(hasLamp = true, hasWindow = true),
}

/**
 * Комната: где что стоит.
 *
 * Все числа напечатаны `tools/pack_room.py` при сборке ресурсов и вставлены сюда
 * как есть. На глаз их не правят: слой в ресурсах обрезан ровно по этим границам,
 * и любая ручная подгонка сдвинет предмет относительно собственной картинки.
 * Дизайнер прислал новый экспорт — перезапустить скрипт и заменить блок целиком.
 */
object Room {

    /** Холст дизайнера. Сцена всегда рисуется в этой пропорции, иначе предметы разъедутся. */
    const val CANVAS_RATIO = 1440f / 2400f

    /**
     * Ось комнаты: середина пола в перспективе.
     *
     * Найдена по доскам, а не по холсту: доски сходятся к одной точке, и та,
     * что идёт строго вертикально, стоит на 0.508 на всех строках пола. На неё
     * встают и питомец в зале, и середина кадра: центральная доска уходит
     * вглубь ровно у него из-под ног, и он стоит посреди комнаты.
     */
    const val ROOM_AXIS_X = 0.508f

    /**
     * Левее этой доли холста кадр не срезает: это левый борт ванны в экспорте
     * (после [BATH_SHIFT] он правее, и слева от ванны виден кусок пола).
     *
     * Холст заполняет экран по высоте, и на телефонах от его ширины видно
     * 0.75–0.81 — по оси комнаты ([ROOM_AXIS_X]) слева не хватает места.
     * Кадр тогда останавливается здесь, и питомец стоит чуть правее середины
     * экрана, зато целы ванна и торшер: у торшера срезается только кончик
     * кольца «Сатурна», шар абажура и подставка начинаются от 0.07.
     */
    const val FRAME_MIN_LEFT = 0.0611f

    /**
     * Шов стены и пола: выше — обои, ниже — доска.
     *
     * Найден построчным доминирующим цветом, а не на глаз: узор ёлочки чередует
     * два зелёных, и переход легко спутать с очередной полосой узора.
     */
    const val FLOOR_TOP = 0.4383f

    /**
     * Насколько ванна с пеной стоит правее, чем в экспорте, — доля ширины холста.
     *
     * Питомец сидит в ванне, и в экспорте она стояла так далеко влево, что
     * он оказывался заметно левее, чем в зале. Сдвиг — сколько позволяет
     * правый край экрана: на самых узких телефонах видно до 0.81 холста, а
     * пена справа доходит до 0.787. Сдвигается и модель ванны в Solids.Bath,
     * иначе тень осталась бы на старом месте.
     *
     * Числа слоёв ниже — как их печатает pack_room.py, сдвиг добавляется
     * к ним отдельно: после нового экспорта не забыть `.shiftedX(BATH_SHIFT)` и `.shiftedY(-BATH_LIFT)`.
     */
    const val BATH_SHIFT = 0.024f

    /**
     * Насколько ванна с пеной выше, чем в экспорте, — доля высоты холста.
     * Верхний борт ванны (0.6192) встаёт вровень с кромкой стола (0.5975): при
     * переходе кухня — ванная верх мебели и питомец остаются на одной высоте.
     */
    const val BATH_LIFT = 0.6192f - 0.5975f

    val Back = RoomLayer(R.drawable.room_back, RelRect(0.0000f, 0.0000f, 1.0000f, 1.0000f))
    val WindowUfo = RoomLayer(R.drawable.room_window_ufo, RelRect(0.4924f, 0.2525f, 0.5979f, 0.3017f))
    val WindowFrame = RoomLayer(R.drawable.room_window_frame, RelRect(0.3500f, 0.0312f, 0.9792f, 0.3675f))
    val Lamp = RoomLayer(R.drawable.room_lamp, RelRect(0.0326f, 0.0408f, 0.2729f, 0.5262f))
    val Table = RoomLayer(R.drawable.room_table, RelRect(0.0965f, 0.5975f, 0.7757f, 0.8087f))
    val Bath = RoomLayer(R.drawable.room_bath, RelRect(0.0611f, 0.6192f, 0.7715f, 0.8433f)).shiftedX(BATH_SHIFT).shiftedY(-BATH_LIFT)
    val BathFoamBack = RoomLayer(R.drawable.room_bath_foam_back, RelRect(0.0972f, 0.5271f, 0.7069f, 0.6671f)).shiftedX(BATH_SHIFT).shiftedY(-BATH_LIFT)
    val BathFoamFront = RoomLayer(R.drawable.room_bath_foam_front, RelRect(0.4049f, 0.5754f, 0.7868f, 0.6587f)).shiftedX(BATH_SHIFT).shiftedY(-BATH_LIFT)

    /** Полоса неба, стыкуется сама с собой; здесь — где она стоит, пока не сдвинулась. */
    val WindowSky = RoomLayer(R.drawable.room_window_sky, RelRect(0.4583f, 0.0854f, 0.8611f, 0.3542f))

    /**
     * Сторона квадрата питомца — доля ширины холста.
     *
     * Одна на кухню и ванную: персонаж не может менять рост, переходя из кухни
     * в ванну. Размер взят от ванны — самого крупного предмета: чаша занимает
     * 0.71 ширины, силуэт питомца — 0.93 своего квадрата, то есть при 0.65
     * он заполняет чашу почти целиком и в комнате читается как главный герой,
     * а не как предмет обстановки.
     */
    const val PET_SIZE = 0.65f

    /**
     * Питомец в зале. Меньше, чем на кухне и в ванной: в зале рядом с ним
     * капсула, а от ширины холста на телефоне видно только 0.75 — при 0.65
     * питомец закрыл бы её целиком.
     */
    private const val LIVING_PET_SIZE = 0.50f

    /**
     * Питомец в игровой. Капсулы рядом нет, и он здесь главный, но мельче, чем
     * на кухне: стоит во весь рост, а не по пояс за столом, и ему нужно место гулять.
     */
    private const val PLAY_PET_SIZE = 0.60f

    /**
     * Ступни питомца в игровой — доля высоты холста. Ближе к зрителю, чем в спальне
     * (0.70): за ним остаётся пол под игрушки, а ряд кнопок внизу его не задевает.
     */
    const val PLAY_PET_FEET = 0.74f

    // ---------- Капсула для сна ----------
    //
    // Дизайнер нарисовал капсулу на весь зал, а стоять ей в углу: правый угол
    // под окном, левый — под шкаф. Поэтому слои капсулы и двери уменьшены
    // в CAPSULE_SCALE раз вокруг правого нижнего угла и переставлены так, что
    // этот угол — в (CAPSULE_RIGHT, CAPSULE_BOTTOM). Числа экспорта ниже — как
    // их печатает pack_room.py.

    /**
     * Во сколько раз капсула меньше, чем в экспорте. При 0.80 крышка закрывала
     * нижнюю половину окна, и НЛО пролетало почти незаметно; при 0.62 она
     * кончается у подоконника, и небо видно почти целиком.
     */
    const val CAPSULE_SCALE = 0.62f

    /** Правый край капсулы: на узких телефонах видно до 0.81 холста. */
    private const val CAPSULE_RIGHT = 0.80f

    /** Низ капсулы: основание на полу за питомцем (его ступни — 0.70), крышка — около 0.32. */
    private const val CAPSULE_BOTTOM = 0.66f

    /** Капсула в экспорте дизайнера. */
    private val CapsuleExport = RelRect(0.1417f, 0.2525f, 0.8403f, 0.7933f)

    private fun capsuleX(x: Float) = CAPSULE_RIGHT - (CapsuleExport.right - x) * CAPSULE_SCALE
    private fun capsuleY(y: Float) = CAPSULE_BOTTOM - (CapsuleExport.bottom - y) * CAPSULE_SCALE

    /** Где на холсте оказывается прямоугольник экспорта капсулы после переноса в угол. */
    private fun inCapsuleCorner(r: RelRect) = RelRect(capsuleX(r.left), capsuleY(r.top), capsuleX(r.right), capsuleY(r.bottom))

    // Объявлены после CapsuleExport: поля object инициализируются по порядку.
    val Capsule = RoomLayer(R.drawable.room_capsule, inCapsuleCorner(CapsuleExport))
    val CapsuleDoor = RoomLayer(R.drawable.room_capsule_door, inCapsuleCorner(RelRect(0.2389f, 0.3267f, 0.7410f, 0.7067f)))

    /**
     * Спящий питомец в капсуле. Стекло внутри рамы — от 352 до 1060 px экспорта,
     * 0.49 его ширины, дно стекла — 1676 px: сюда встают ступни. Самый широкий
     * силуэт (Рогатик, 0.99 квадрата) при 0.50 ширины экспорта ровно ложится в стекло.
     */
    val PetInCapsule: RelRect = run {
        val size = 0.50f * CAPSULE_SCALE
        val centre = capsuleX(0.4903f)
        val top = capsuleY(0.6983f) - 0.87f * size * CANVAS_RATIO
        RelRect(centre - size / 2f, top, centre + size / 2f, top + size * CANVAS_RATIO)
    }

    private fun petSize(spot: RoomSpot): Float = when (spot) {
        RoomSpot.LIVING -> LIVING_PET_SIZE
        RoomSpot.PLAY -> PLAY_PET_SIZE
        RoomSpot.KITCHEN, RoomSpot.BATH -> PET_SIZE
    }

    /**
     * Верх квадрата питомца в каждой комнате — доля высоты холста.
     *
     * Единственные числа в файле, снятые не замером: питомца в экспортах
     * обстановки нет и промерять нечего. Но привязаны они к замеренным
     * границам предметов. В силуэте ступни приходятся примерно на 0.87 высоты
     * квадрата, макушка — на 0.12, отсюда и отсчёт.
     */
    private fun petTop(spot: RoomSpot): Float = when (spot) {
        // Ступни (0.87 квадрата) на полу перед капсулой: 0.70 ближе к зрителю,
        // чем её основание (0.66), — питомец стоит перед ней, а не в ней.
        RoomSpot.LIVING -> 0.70f - 0.87f * LIVING_PET_SIZE * CANVAS_RATIO

        RoomSpot.PLAY -> PLAY_PET_FEET - 0.87f * PLAY_PET_SIZE * CANVAS_RATIO

        // Стол непрозрачен ниже своей кромки 0.5975 — за ней прячется нижняя
        // треть питомца, и получается, что он сидит за столом. Выше зала
        // ровно настолько, чтобы столешница пришлась под морду, а не по глаза.
        RoomSpot.KITCHEN -> 0.320f

        // Как на кухне: борт ванны поднят вровень с кромкой стола ([BATH_LIFT]),
        // и питомец при переходе остаётся на месте. Ступни (0.66) ещё в чаше,
        // которая перекрывает всё ниже 0.642 (борт 0.598 плюс кромка).
        RoomSpot.BATH -> 0.320f
    }

    /**
     * Середина питомца по горизонтали — доля ширины холста.
     *
     * Питомец стоит как можно ближе к одному месту во всех комнатах, чтобы
     * при переключении не скакал по экрану. В зале — слева от капсулы, а стол
     * и ванна стоят левее, и там он встаёт настолько близко к оси, насколько
     * позволяют их правые края: самый широкий силуэт (Рогатик, до 0.99
     * квадрата) не должен вылезать за край стола (0.7757) и за борт ванны
     * (0.7715 в экспорте). Проверено по пикселям всех пяти питомцев: 0.46
     * уже выходит за борт. В ванне к этому добавляется её сдвиг [BATH_SHIFT].
     */
    private fun petCentre(spot: RoomSpot): Float = when (spot) {
        // Левее середины экрана: справа капсула, и питомец её почти не заслоняет.
        RoomSpot.LIVING -> 0.34f
        // Левее середины экрана, как на концепте: справа место под ящик с игрушками.
        // Игровая отражена (RoomScene, mirrorAxis), поэтому в её холсте он правее:
        // 0.57 до отражения — около трети экрана слева на узком телефоне.
        RoomSpot.PLAY -> 0.57f
        RoomSpot.KITCHEN -> 0.453f
        RoomSpot.BATH -> 0.453f + BATH_SHIFT
    }

    /**
     * Где стоит питомец в текущей комнате.
     *
     * Питомец рисуется квадратом по ширине холста, поэтому работают `left`,
     * `top` и `width`; `bottom` считается тут же, чтобы прямоугольник не врал.
     */
    fun petGround(spot: RoomSpot): RelRect {
        val centre = petCentre(spot)
        val top = petTop(spot)
        val size = petSize(spot)
        return RelRect(
            left = centre - size / 2f,
            top = top,
            right = centre + size / 2f,
            // Квадрат по ширине: в долях высоты его сторона меньше во столько же
            // раз, во сколько холст выше своей ширины.
            bottom = top + size * CANVAS_RATIO,
        )
    }

    /** Окно изнутри рамы: по нему летит НЛО и за него не должен вылезать. */
    val WindowHole = RelRect(0.4278f, 0.0854f, 0.8806f, 0.3542f)
}
